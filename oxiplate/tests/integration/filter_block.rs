use alloc::format;

use oxiplate::prelude::*;

#[test]
fn basic_lower() {
    #[derive(Oxiplate)]
    #[oxiplate_inline(
        r#"
{%- filter raw | lower -%}
    Hello World!
{%- endfilter -%}
"#
    )]
    struct Data;

    assert_eq!(format!("{Data}"), "hello world!");
}

#[test]
fn basic_lower_upper() {
    #[derive(Oxiplate)]
    #[oxiplate_inline(
        r#"
{%- filter raw | >lower | upper -%}
    Hello World!
{%- endfilter -%}
"#
    )]
    struct Data;

    assert_eq!(format!("{Data}"), "HELLO WORLD!");
}

/// Test to ensure content is output as-is when `raw` is set.
/// Uppercase HTML tags isn't really supposed to be a use-case,
/// but it does essentially test what would happen
/// if that HTML was generated by one of the filters.
/// Easier than writing a filter
/// that generates HTML and escapes the content passed to it.
#[test]
fn writs_with_html() {
    #[derive(Oxiplate)]
    #[oxiplate_inline(
        r#"
{%- filter raw | upper -%}
    {{ message }}
{%- endfilter -%}
"#
    )]
    struct Data {
        message: &'static str,
    }

    assert_eq!(
        format!(
            "{}",
            Data {
                message: "<strong>Hello</strong> World!"
            }
        ),
        "<STRONG>HELLO</STRONG> WORLD!"
    );
}

#[test]
fn writs_with_unsafe_chars() {
    #[derive(Oxiplate)]
    #[oxiplate_inline(
        r#"
{%- filter html.text | upper -%}
    {{ message }}
{%- endfilter -%}
"#
    )]
    struct Data {
        message: &'static str,
    }

    assert_eq!(
        format!(
            "{}",
            Data {
                message: "<Hello> World!"
            }
        ),
        "&lt;HELLO> WORLD!"
    );
}
